import { describe, it, expect } from 'vitest';
import { generateICS, generateMarkdownSummary } from '../utils/exportUtils';
import { MOCK_BLUEPRINTS } from '../data/mockBlueprints';
import { ICS_PRODID } from '../constants';
import { EventPlan } from '../types/event';

describe('Export Suite Operations', () => {
  const samplePlan = MOCK_BLUEPRINTS['royal-wedding'];

  it('generates valid RFC 5545 iCalendar (.ics) formatted content', () => {
    const ics = generateICS(samplePlan);
    expect(ics).toContain('BEGIN:VCALENDAR');
    expect(ics).toContain('VERSION:2.0');
    expect(ics).toContain(`PRODID:${ICS_PRODID}`);
    expect(ics).toContain('BEGIN:VEVENT');
    expect(ics).toContain('SUMMARY:[Arrival]');
    expect(ics).toContain('END:VCALENDAR');
  });

  it('generates rich markdown summary with all essential sections', () => {
    const md = generateMarkdownSummary(samplePlan);
    expect(md).toContain('# The Grand Jaipur Heritage Royal Wedding');
    expect(md).toContain('## 💰 Budget Breakdown');
    expect(md).toContain('## ⏱️ Run-of-Show Timeline');
    expect(md).toContain('## 📋 Critical Vendor & Procurement Checklist');
    expect(md).toContain('## 🛡️ Risk & Contingency Matrix');
    expect(md).toContain('Generated by AuraPlan AI Core');
  });

  it('gracefully handles plans without explicit eventDate by defaulting to current date', () => {
    const datelessPlan: EventPlan = {
      ...samplePlan,
      eventDate: undefined,
    };
    const ics = generateICS(datelessPlan);
    expect(ics).toContain('BEGIN:VCALENDAR');
    expect(ics).toContain('BEGIN:VEVENT');
    expect(ics).toContain('END:VCALENDAR');

    const md = generateMarkdownSummary(datelessPlan);
    expect(md).toContain('> **Date:** Flexible / TBD');
  });

  it('escapes special characters and format markers safely in markdown export', () => {
    const specialPlan: EventPlan = {
      ...samplePlan,
      eventSummary: {
        ...samplePlan.eventSummary,
        title: 'Tech & Art Summit <2026> "Celebration"',
        tagline: 'Code * Fast & Break * Nothing',
      },
      specialRequirements: 'Wheelchair access & gluten-free options',
    };
    const md = generateMarkdownSummary(specialPlan);
    expect(md).toContain('Tech & Art Summit <2026> "Celebration"');
    expect(md).toContain('Wheelchair access & gluten-free options');
  });
});
